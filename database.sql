CREATE DATABASE IF NOT EXISTS abshiro_masjid CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE abshiro_masjid;
CREATE TABLE IF NOT EXISTS prayer_times(
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 prayer_date DATE NOT NULL UNIQUE,
 fajr TIME NOT NULL,dhuhr TIME NOT NULL,asr TIME NOT NULL,
 maghrib TIME NOT NULL,isha TIME NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
